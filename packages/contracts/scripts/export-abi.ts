// Copies the compiled LocationDrop ABI to the packages that consume it:
// the web app (as a typed `as const` module) and the subgraph (as JSON).
import { mkdir, readFile, writeFile } from "node:fs/promises";

const artifactUrl = new URL(
  "../artifacts/contracts/LocationDrop.sol/LocationDrop.json",
  import.meta.url,
);
const { abi } = JSON.parse(await readFile(artifactUrl, "utf8"));
const json = JSON.stringify(abi, null, 2);

const generatedDir = new URL("../generated/", import.meta.url);
await mkdir(generatedDir, { recursive: true });
await writeFile(
  new URL("abi.ts", generatedDir),
  `// Generated by scripts/export-abi.ts. Do not edit.\nexport const locationDropAbi = ${json} as const;\n`,
);

const subgraphAbis = new URL("../../subgraph/abis/", import.meta.url);
await mkdir(subgraphAbis, { recursive: true });
await writeFile(new URL("LocationDrop.json", subgraphAbis), `${json}\n`);

console.log("Exported LocationDrop ABI");
